/** Lamps for the big figure: digits, spaces and ₽, fourteen rows high, two dark lamps between characters. */
export function ledBig(text: string): LedGlyphs {
  const chars = [...text].map((c) => BIG[c] ?? BIG[' ']);
  const w = chars.reduce((sum, rows) => sum + rows[0].length, 0) + (chars.length - 1) * 2;
  const bits = new Uint8Array(w * 14);
  let x0 = 0;
  for (const rows of chars) {
    rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && (bits[y * w + x0 + x] = 1)));
    x0 += rows[0].length + 2;
  }
  return { w, h: 14, bits };
}
