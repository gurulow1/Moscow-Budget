export interface LedGlyphs {
  w: number;
  h: number;
  bits: Uint8Array;
}

/** Lamps for a line of text, seven rows high, one dark lamp between letters. Unknown characters become a space. */
export function ledText(text: string): LedGlyphs {
  const chars = [...text.toUpperCase().replace(/Ё/g, 'Е')].map((c) => (GLYPHS[c] ?? GLYPHS[' ']).split(' '));
  const w = chars.reduce((sum, rows) => sum + rows[0].length + 1, 0);
  const bits = new Uint8Array(w * 7);
  let x0 = 0;
  for (const rows of chars) {
    rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && (bits[y * w + x0 + x] = 1)));
    x0 += rows[0].length + 1;
  }
  return { w, h: 7, bits };
}

